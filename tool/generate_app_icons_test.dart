// Renders the Duet logo (lib/core/widgets/duet_logo.dart) into every launcher icon.
//
//   flutter test tool/generate_app_icons_test.dart
//
// Writes:
//   android/app/src/main/res/mipmap-*/ic_launcher[_love|_friends].png        (legacy icons)
//   android/app/src/main/res/mipmap-*/ic_launcher*_{foreground,background,monochrome}.png
//   android/app/src/main/res/mipmap-anydpi-v26/ic_launcher*.xml                (adaptive icons)
//   ios/Runner/Assets.xcassets/AppIcon.appiconset/*.png                        (General, opaque)
//   branding/duet_logo_<mode>_1024.png, branding/app_icons_preview.png
import 'dart:io';
import 'dart:typed_data';
import 'dart:ui' as ui;

import 'package:duet/core/theme/app_mode.dart';
import 'package:duet/core/widgets/duet_logo.dart';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:image/image.dart' as img;

const _res = 'android/app/src/main/res';
const _legacySizes = {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192};
const _adaptiveSizes = {'mdpi': 108, 'hdpi': 162, 'xhdpi': 216, 'xxhdpi': 324, 'xxxhdpi': 432};

String iconName(AppMode mode) => mode == AppMode.general ? 'ic_launcher' : 'ic_launcher_${mode.name}';

Future<Uint8List> _encode(ui.Picture picture, int width, int height) async {
  final image = await picture.toImage(width, height);
  final data = await image.toByteData(format: ui.ImageByteFormat.png);
  return data!.buffer.asUint8List();
}

Future<Uint8List> render(AppMode mode, LogoStyle style, int size) {
  final recorder = ui.PictureRecorder();
  final canvas = Canvas(recorder);
  DuetLogoPainter(mode: mode, style: style).paint(canvas, Size(size.toDouble(), size.toDouble()));
  return _encode(recorder.endRecording(), size, size);
}

/// How a launcher shows the adaptive icon: back + front layers, centre 2/3 visible, circle mask.
void paintAdaptivePreview(Canvas canvas, AppMode mode, Offset topLeft, double diameter) {
  final layer = diameter * 1.5;
  canvas.save();
  canvas.clipPath(Path()..addOval(topLeft & Size(diameter, diameter)));
  canvas.translate(topLeft.dx - diameter * 0.25, topLeft.dy - diameter * 0.25);
  DuetLogoPainter(mode: mode, style: LogoStyle.background).paint(canvas, Size(layer, layer));
  DuetLogoPainter(mode: mode, style: LogoStyle.foreground).paint(canvas, Size(layer, layer));
  canvas.restore();
}

void _write(String path, List<int> bytes) {
  final file = File(path);
  file.parent.createSync(recursive: true);
  file.writeAsBytesSync(bytes);
}

String _adaptiveXml(String name) => '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_app_icons_test.dart -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/${name}_background" />
    <foreground android:drawable="@mipmap/${name}_foreground" />
    <monochrome android:drawable="@mipmap/${name}_monochrome" />
</adaptive-icon>
''';

void main() {
  testWidgets('generate app icons', (tester) async {
    await tester.runAsync(() async {
      for (final mode in AppMode.values) {
        final name = iconName(mode);
        for (final MapEntry(key: density, value: size) in _legacySizes.entries) {
          _write('$_res/mipmap-$density/$name.png', await render(mode, LogoStyle.badge, size));
        }
        for (final MapEntry(key: density, value: size) in _adaptiveSizes.entries) {
          _write('$_res/mipmap-$density/${name}_foreground.png', await render(mode, LogoStyle.foreground, size));
          _write('$_res/mipmap-$density/${name}_background.png', await render(mode, LogoStyle.background, size));
          _write('$_res/mipmap-$density/${name}_monochrome.png', await render(mode, LogoStyle.monochrome, size));
        }
        _write('$_res/mipmap-anydpi-v26/$name.xml', _adaptiveXml(name).codeUnits);
        _write('branding/duet_logo_${mode.name}_1024.png', await render(mode, LogoStyle.badge, 1024));
      }

      // iOS uses the General icon; App Store icons must be opaque (no alpha channel).
      final iosDir = Directory('ios/Runner/Assets.xcassets/AppIcon.appiconset');
      final pattern = RegExp(r'Icon-App-([\d.]+)x[\d.]+@(\d)x\.png$');
      var iosCount = 0;
      for (final file in iosDir.listSync().whereType<File>()) {
        final match = pattern.firstMatch(file.path);
        if (match == null) continue;
        final px = (double.parse(match.group(1)!) * int.parse(match.group(2)!)).round();
        final png = await render(AppMode.general, LogoStyle.square, px);
        final opaque = img.decodePng(png)!.convert(numChannels: 3);
        _write(file.path, img.encodePng(opaque));
        iosCount++;
      }
      expect(iosCount, greaterThan(10));

      // Preview sheet: row 1 = badges, row 2 = adaptive icons as a launcher shows them,
      // row 3 = Android 13+ "themed icons" (monochrome layer tinted by the system).
      const cell = 300.0;
      const gap = 60.0;
      const width = gap + 3 * (cell + gap);
      const height = gap + 3 * (cell + gap);
      final recorder = ui.PictureRecorder();
      final canvas = Canvas(recorder);
      canvas.drawRect(const Rect.fromLTWH(0, 0, width, height), Paint()..color = const Color(0xFF202124));
      for (final (i, mode) in AppMode.values.indexed) {
        final x = gap + i * (cell + gap);
        canvas.save();
        canvas.translate(x, gap);
        DuetLogoPainter(mode: mode).paint(canvas, const Size(cell, cell));
        canvas.restore();
        paintAdaptivePreview(canvas, mode, Offset(x, gap * 2 + cell), cell);

        final themedRect = Offset(x, gap * 3 + cell * 2) & const Size(cell, cell);
        canvas.drawOval(themedRect, Paint()..color = const Color(0xFF2E3440));
        canvas.save();
        canvas.clipPath(Path()..addOval(themedRect));
        canvas.saveLayer(
          themedRect,
          Paint()..colorFilter = const ColorFilter.mode(Color(0xFFD8DEE9), BlendMode.srcIn),
        );
        canvas.translate(themedRect.left - cell * 0.25, themedRect.top - cell * 0.25);
        DuetLogoPainter(mode: mode, style: LogoStyle.monochrome).paint(canvas, const Size(cell * 1.5, cell * 1.5));
        canvas.restore();
        canvas.restore();
      }
      _write('branding/app_icons_preview.png', await _encode(recorder.endRecording(), width.toInt(), height.toInt()));
    });
  });
}
